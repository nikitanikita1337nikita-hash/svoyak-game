Object.entries(extraQuestionBank).forEach(([category, questions]) => {
  questionBank[category] = [
    ...(questionBank[category] || []),
    ...questions
  ];
});

type Player = {
  id: string;
  name: string;
  score: number;
};

type ActiveQuestion = {
  category: string;
  points: number;
  question: string;
  answer: string;
  revealed: boolean;
  deadlineAt: number | null;
  expired: boolean;
};

type Room = {
  code: string;
  players: Player[];
  hostId: string;
  categories: string[];
  activeQuestion: ActiveQuestion | null;
  usedQuestions: string[];
  previousGameQuestions: string[];
  usedCells: string[];
  timerSeconds: number | null;
};

const socket = io(`http://${window.location.hostname}:3001`, {
  autoConnect: false
});

export default function App() {
  const [connected, setConnected] = useState(false);
  const [name, setName] = useState('');
  const [code, setCode] = useState('');
  const [room, setRoom] = useState<Room | null>(null);
  const [error, setError] = useState('');
  const [now, setNow] = useState(Date.now());

  useEffect(() => {
    socket.connect();

    socket.on('connect', () => setConnected(true));
    socket.on('disconnect', () => setConnected(false));
    socket.on('room-updated', (data: Room) => setRoom(data));

    return () => {
      socket.off('connect');
      socket.off('disconnect');
      socket.off('room-updated');
      socket.disconnect();
    };
  }, []);

  useEffect(() => {
    if (!room?.activeQuestion?.deadlineAt) return;

    const interval = setInterval(() => {
      setNow(Date.now());
    }, 250);

    return () => clearInterval(interval);
  }, [room?.activeQuestion?.deadlineAt]);

  const isHost = room?.hostId === socket.id;

  const sortedPlayers = [...(room?.players || [])].sort(
    (a, b) => b.score - a.score
  );

  const createRoom = () => {
    setError('');

    socket.emit('create-room', name, (result: any) => {
      if (!result.success) setError(result.error);
    });
  };

  const joinRoom = () => {
    setError('');

    socket.emit('join-room', { code, name }, (result: any) => {
      if (!result.success) setError(result.error);
    });
  };

  const setTimer = (seconds: number | null) => {
    if (!room || !isHost) return;

    socket.emit('set-timer', {
      code: room.code,
      seconds
    }, (result: any) => {
      if (!result.success) setError(result.error);
    });
  };

  const toggleCategory = (category: string) => {
    if (!room || !isHost) return;

    let next = [...room.categories];

    if (next.includes(category)) {
      next = next.filter(item => item !== category);
    } else {
      if (next.length >= 6) return;
      next.push(category);
    }

    socket.emit('set-categories', {
      code: room.code,
      categories: next
    });
  };

  const openQuestion = (category: string, index: number) => {
    if (!room || !isHost) return;

    const allQuestions = questionBank[category] || [];
    const used = new Set(room.usedQuestions || []);
    const previous = new Set(room.previousGameQuestions || []);

    const unused = allQuestions.filter(item => {
      const key = `${category}|${item.question}`;
      return !used.has(key) && !previous.has(key);
    });

    const available = unused.length
      ? unused
      : allQuestions.filter(item =>
          !used.has(`${category}|${item.question}`)
        );

    const cellKey = `${category}|${points[index]}`;

    if (room.usedCells?.includes(cellKey)) {
      setError('Этот вопрос уже использован.');
      return;
    }

    if (!available.length) {
      setError('В этой категории закончились вопросы.');
      return;
    }

    const question =
      available[Math.floor(Math.random() * available.length)];

    setError('');

    socket.emit('open-question', {
      code: room.code,
      category,
      points: points[index],
      question: question.question,
      answer: question.answer
    }, (result: any) => {
      if (!result.success) setError(result.error);
    });
  };

  const awardPoints = (playerId: string) => {
    if (!room) return;

    socket.emit('award-points', {
      code: room.code,
      playerId
    }, (result: any) => {
      if (!result.success) setError(result.error);
    });
  };

  const finishQuestion = () => {
    if (!room) return;

    socket.emit('finish-question', { code: room.code }, (result: any) => {
      if (!result.success) setError(result.error);
    });
  };

  const startNewGame = () => {
    if (!room || !isHost) return;

    if (!window.confirm('Начать новую игру? Очки всех игроков обнулятся.')) {
      return;
    }

    setError('');

    socket.emit('new-game', { code: room.code }, (result: any) => {
      if (!result.success) setError(result.error);
    });
  };

  if (!room) {
    return (
      <main className="container">
        <h1>СВОЯК</h1>

        <p>
          {connected
            ? '🟢 Подключено к серверу'
            : '🔴 Подключение...'}
        </p>

        <input
          className="game-input"
          placeholder="Твоё имя"
          value={name}
          onChange={e => setName(e.target.value)}
        />

        <button
          onClick={createRoom}
          disabled={!connected || !name.trim()}
        >
          Создать комнату
        </button>

        <div>
          <input
            className="game-input"
            placeholder="Код комнаты"
            value={code}
            onChange={e => setCode(e.target.value)}
          />

          <button
            onClick={joinRoom}
            disabled={!connected || !name.trim() || !code.trim()}
          >
            Войти в комнату
          </button>
        </div>

        {error && <p className="error">{error}</p>}
      </main>
    );
  }

  const activeQuestion = room.activeQuestion;

  const remainingSeconds =
    activeQuestion?.deadlineAt !== null &&
    activeQuestion?.deadlineAt !== undefined
      ? Math.max(
          0,
          Math.ceil((activeQuestion.deadlineAt - now) / 1000)
        )
      : null;

  const timerText =
    remainingSeconds === null
      ? 'Без таймера'
      : `${String(Math.floor(remainingSeconds / 60)).padStart(2, '0')}:${String(remainingSeconds % 60).padStart(2, '0')}`;

  return (
    <main className="container">
      <h1>СВОЯК</h1>
      <h2>Комната: {room.code}</h2>

      <section className="leaderboard">
        <h2>🏆 Таблица результатов</h2>

        {sortedPlayers.map((player, index) => (
          <div
            key={player.id}
            className={`leaderboard-item ${
              index === 0 ? 'leader' : ''
            }`}
          >
            <span className="player-rank">
              {index === 0
                ? '🥇'
                : index === 1
                  ? '🥈'
                  : index === 2
                    ? '🥉'
                    : `${index + 1}.`}
            </span>

            <strong>{player.name}</strong>

            <span className="player-score">
              {player.score} очков
            </span>
          </div>
        ))}
      </section>

      {activeQuestion ? (
        <section className="question-panel">
          <h2>{activeQuestion.category}</h2>
          <h3>{activeQuestion.points} очков</h3>

          <p>{activeQuestion.question}</p>

          {!activeQuestion.revealed && (
            <div
              className="question-timer"
              style={{
                fontSize: '36px',
                fontWeight: 'bold',
                margin: '20px'
              }}
            >
              {activeQuestion.expired ||
              (remainingSeconds !== null && remainingSeconds <= 0)
                ? 'Время вышло!'
                : timerText}
            </div>
          )}

          {isHost ? (
            <>
              <h3>Правильный ответ:</h3>
              <p>{activeQuestion.answer}</p>

              <h3>
                Кому начислить {activeQuestion.points} очков?
              </h3>

              {room.players.map(player => (
                <button
                  key={player.id}
                  onClick={() => awardPoints(player.id)}
                >
                  {player.name}
                </button>
              ))}

              <button onClick={finishQuestion}>
                Закрыть вопрос без начисления
              </button>
            </>
          ) : (
            <p>Ждём ответа ведущего...</p>
          )}
        </section>
      ) : (
        <>
          {isHost ? (
            <>
              <button onClick={startNewGame}>
                Начать новую игру
              </button>

              <section className="timer-settings">
                <h2>⏱ Время на ответ</h2>

                <p>
                  Выбрано: {
                    room.timerSeconds === null
                      ? 'Без таймера'
                      : room.timerSeconds === 60
                        ? '1 минута'
                        : '1 минута 30 секунд'
                  }
                </p>

                <button
                  className={room.timerSeconds === 60 ? 'selected' : ''}
                  onClick={() => setTimer(60)}
                >
                  1 минута
                </button>

                <button
                  className={room.timerSeconds === 90 ? 'selected' : ''}
                  onClick={() => setTimer(90)}
                >
                  1 минута 30 секунд
                </button>

                <button
                  className={room.timerSeconds === null ? 'selected' : ''}
                  onClick={() => setTimer(null)}
                >
                  Без таймера
                </button>
              </section>

              <h2>Выбери 6 категорий</h2>
              <p>Выбрано: {room.categories.length}/6</p>

              {room.categories.length < 6 && (
                <div className="categories">
                  {categories.map(category => (
                    <button
                      key={category}
                      className={
                        room.categories.includes(category) ? 'selected' : ''
                      }
                      onClick={() => toggleCategory(category)}
                    >
                      {room.categories.includes(category) ? '✓ ' : ''}
                      {category}
                    </button>
                  ))}
                </div>
              )}

              {room.categories.length === 6 && (
                <>
                  <h2>Игровое поле</h2>

                  <div className="game-board">
                    {room.categories.map(category => (
                      <div className="game-column" key={category}>
                        <h3>{category}</h3>

                        {points.map((value, index) => {
                          const used = room.usedCells?.includes(
                            `${category}|${value}`
                          );

                          return (
                            <button
                              key={value}
                              disabled={used}
                              className={used ? 'used-question' : ''}
                              onClick={() => openQuestion(category, index)}
                            >
                              {used ? '✓' : value}
                            </button>
                          );
                        })}
                      </div>
                    ))}
                  </div>

                  <p>Выбери стоимость вопроса, чтобы открыть его.</p>
                </>
              )}
            </>
          ) : (
            <>
              <h2>Категории ведущего</h2>

              <p>
                Таймер: {
                  room.timerSeconds === null
                    ? 'Без таймера'
                    : room.timerSeconds === 60
                      ? '1 минута'
                      : '1 минута 30 секунд'
                }
              </p>

              {room.categories.length === 0 ? (
                <p>Ведущий пока выбирает категории...</p>
              ) : room.categories.length < 6 ? (
                <>
                  <p>
                    Ведущий выбирает категории: {room.categories.length}/6
                  </p>

                  {room.categories.map(category => (
                    <p key={category}>🎯 {category}</p>
                  ))}
                </>
              ) : (
                <>
                  <h2>Игровое поле</h2>

                  <div className="game-board">
                    {room.categories.map(category => (
                      <div className="game-column" key={category}>
                        <h3>{category}</h3>

                        {points.map(value => {
                          const used = room.usedCells?.includes(
                            `${category}|${value}`
                          );

                          return (
                            <div
                              className={`player-points ${
                                used ? 'used-question' : ''
                              }`}
                              key={value}
                            >
                              {used ? '✓' : value}
                            </div>
                          );
                        })}
                      </div>
                    ))}
                  </div>

                  <p>Ведущий выбирает вопросы.</p>
                </>
              )}
            </>
          )}
        </>
      )}

      {error && <p className="error">{error}</p>}
    </main>
  );
}
